function systemLocale(): Locale {
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function resolveLocale(preference: LocalePreference): Locale {
  return preference === "system" ? systemLocale() : preference;
}

interface I18nValue {
  locale: Locale;
  preference: LocalePreference;
  setPreference: (preference: LocalePreference) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ preference = "system", children }: { preference?: LocalePreference; children: ReactNode }) {
  const [localPreference, setLocalPreference] = useState<LocalePreference>(() => {
    if (typeof window === "undefined") return preference;
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return stored === "en" || stored === "zh-CN" || stored === "system" ? stored : preference;
  });
  useEffect(() => window.localStorage.setItem(STORAGE_KEY, localPreference), [localPreference]);
  const locale = resolveLocale(localPreference);
  const value = useMemo(
    () => ({ locale, preference: localPreference, setPreference: setLocalPreference, t: (key: string) => translations[locale][key] ?? key }),
    [locale, localPreference],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n outside I18nProvider");
  return value;
}

export function useT() {
  return useI18n().t;
}
